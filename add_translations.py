LANG_ORDER = ["de", "it", "pt", "ru", "zh", "tr", "ur", "hi", "fa", "id", "ja", "ko", "th"]

def build_block(code, translations):
    lines = [f"  {code}: {{"]
    keys = list(translations.keys())
    for i, k in enumerate(keys):
        v = translations[k]
        # Escape backslashes and double quotes for JS
        v_escaped = v.replace("\\", "\\\\").replace('"', '\\"')
        comma = "," if i < len(keys) - 1 else ""
        lines.append(f'    {k}: "{v_escaped}"{comma}')
    lines.append("  },")
    return "\n".join(lines)

