    def handle_matching_flow(self, message):
        """معالجة تدفق المطابقة — كل الخطوات في مكان واحد"""
        user_id = message['from']['id']
        chat_id = message['chat']['id']
        state = self.user_states.get(user_id, '')
        text = message.get('text', '').strip()
        user = self.find_user(user_id)
        if not user:
            return
        lang = user.get('language', 'ar')

        # === match_enter_data: المبلغ ← المحفظة ← المعرف ===
        if isinstance(state, dict) and state.get('step') == 'match_enter_data':
            text_msg = message.get('text', '').strip()

            if text_msg in [self.tr('a0009_إلغاء', lang), self.tr('a0010_إلغاء', lang), self.tr('a0011_الغاء', lang), '🔙', self.tr('a0083_القائمة_الرئيسية', lang)]:
                del self.user_states[user_id]
                self.handle_start(message)
                return

            substep = state.get('substep', 'amount')

            if substep == 'amount':
                try:
                    amount = float(text_msg)
                    if amount <= 0:
                        self.send_message(chat_id, self.tr('a0144_المبلغ_يجب', lang))
                        return
                except ValueError:
                    self.send_message(chat_id, self.tr('a0145_اكتب_مبلغاً', lang))
                    return
                state['amount'] = str(amount)
                state['substep'] = 'wallet'
                self.user_states[user_id] = state
                kb = {'keyboard': [[{'text': '❌ إلغاء'}]], 'resize_keyboard': True, 'one_time_keyboard': True}
                self.send_message(chat_id,
                    f"✅ المبلغ: <code>{amount}</code>\n"
                    f"🔒 <b>بياناتك محفوظة بأمان</b>\n\n"
                    f"2️⃣ اكتب <b>رقم محفظتك</b>:\n\n"
                    f"⚠️ <b>لا ترسل المال قبل أن يؤكد لك ذلك</b>", kb)
                return

            if substep == 'wallet':
                wallet_number = self.sanitize_input(text_msg)
                if len(wallet_number) < 5:
                    self.send_message(chat_id, self.tr('a0146_رقم_المحفظة', lang))
                    return
                state['wallet_number'] = wallet_number
                state['substep'] = 'account'
                self.user_states[user_id] = state
                kb = {'keyboard': [[{'text': '❌ إلغاء'}]], 'resize_keyboard': True, 'one_time_keyboard': True}
                self.send_message(chat_id,
                    f"✅ المحفظة: <code>{wallet_number}</code> 👈 اضغط للنسخ\n"
                    f"🔒 <b>بياناتك محفوظة بأمان</b>\n\n"
                    f"3️⃣ اكتب <b>معرف حسابك</b> (ID):\n\n"
                    f"⚠️ <b>لا ترسل المال قبل أن يؤكد لك ذلك</b>", kb)
                return

            if substep == 'account':
                account_id = self.sanitize_input(text_msg)
                if len(account_id) < 2:
                    self.send_message(chat_id, self.tr('a0404_معرف_الحساب', lang))
                    return

                # ✅ تأكيد حفظ البيانات
                self.send_message(chat_id,
                    f"✅ معرف الحساب: <code>{account_id}</code> 👈 اضغط للنسخ\n"
                    f"🔒 <b>جميع بياناتك محفوظة بأمان</b>\n\n"
                    f"⏳ جارٍ إنشاء طلبك ومراجعته من الإدارة...\n\n"
                    f"⚠️ <b>لا ترسل المال قبل أن يؤكد لك ذلك</b>")

                amount = state.get('amount', '0')
                wallet_number = state.get('wallet_number', '')
                match_type = state.get('type', 'deposit')
                company_id = state.get('company_id', '')
                company_name = state.get('company_name', '')

                # إنشاء طلب المطابقة
                try:
                    req_id, error = self.match_manager.create_match_request(
                        str(user_id), user.get('customer_id', ''), match_type,
                        str(amount), user.get('currency', 'SAR'),
                        str(company_id), company_name, ''
                    )
                    if error:
                        self.send_message(chat_id, f"❌ {error}", self.main_keyboard(lang, user_id))
                        del self.user_states[user_id]
                        return
                except Exception as e:
                    logger.error(f"خطأ في create_match_request: {e}")
                    self.send_message(chat_id,
                        self.tr('a0405_حدث_خطأ', 'ar'),
                        self.main_keyboard(lang, user_id))
                    del self.user_states[user_id]
                    return

                # البحث عن مطابقة
                request = None
                match = None
                try:
                    request = self.match_manager.get_active_request_by_user(str(user_id))
                    if request:
                        match = self.match_manager.find_match(request)
                except Exception as e:
                    logger.error(f"خطأ في find_match: {e}")

                if request and match:
                    try:
                        match_id = self.match_manager.create_match(request, match)
                        self._notify_match_created(match_id)
                        del self.user_states[user_id]
                        return
                    except Exception as e:
                        logger.error(f"خطأ في create_match: {e}")

                # لا توجد مطابقة — العميل ينتظر موافقة الإدارة + الأدمن يصبح الطرف الآخر تلقائياً
                type_ar = self.tr('a0390_إيداع', 'ar') if match_type == 'deposit' else self.tr('a0391_سحب', 'ar')
                nav_btns = [[{'text': '🔄 المطابقة', 'callback_data': 'match_back_main'},
                             {'text': '🏠 القائمة', 'callback_data': 'main_menu'}]]
