    def update_transaction_status(self, trans_id, new_status, note='', admin_id=''):
        """تحديث حالة المعاملة"""
        transactions = []
        success = False
        
        try:
            with open('transactions.csv', 'r', encoding='utf-8-sig') as f:
                reader = csv.DictReader(f)
                for row in reader:
                    if row['id'] == trans_id:
                        row['status'] = new_status
                        if note:
                            row['admin_note'] = note
                        if admin_id:
                            row['processed_by'] = admin_id
                        success = True
                    transactions.append(row)
            
            if success:
                with open('transactions.csv', 'w', newline='', encoding='utf-8-sig') as f:
                    fieldnames = [
                        'id',
                        'customer_id',
                        'telegram_id',
                        'name',
                        'type',
                        'company',
                        'wallet_number',
                        'amount',
                        'exchange_address',
                        'status',
                        'date',
                        'admin_note',
                        'processed_by',
                        'currency'
                    ]
                    writer = csv.DictWriter(f, fieldnames=fieldnames)
                    writer.writeheader()
                    writer.writerows(transactions)

        except:
            pass
        
        # ── Smart Engine: Fire webhook + chain event for transaction status change ──
        if success and getattr(self, 'smart_engine', None):
            try:
                # Find the transaction to get user info
                trans = None
                for t in transactions:
                    if t['id'] == trans_id:
                        trans = t
                        break
                if trans:
                    event_type = f"transaction_{new_status}"
                    extra = {
                        'trans_id': trans_id,
                        'type': trans.get('type', ''),
                        'amount': trans.get('amount', ''),
                        'user_id': trans.get('telegram_id', ''),
                        'status': new_status,
                    }
                    self.smart_engine.fire_event(event_type, trans.get('telegram_id', ''), extra)
                    self.smart_engine.trigger_webhook(event_type, extra)
            except Exception:
                pass
        
        return success
    
