import logging

logger = logging.getLogger(__name__)


class MessageDispatcherMixin:

    def process_message(self, message):
        """معالج الرسائل الرئيسي"""
        if 'text' not in message and 'contact' not in message and 'photo' not in message and 'document' not in message and 'video' not in message and 'sticker' not in message:
            return

        # فحص هل الرسالة من قناة/مجموعة البوت مشرف بها ← إعادة نشر تلقائي
        chat_type = message.get('chat', {}).get('type', '')
        if chat_type in ('channel', 'group', 'supergroup'):
            # فحص هل هي قناة مصدرية (scrape) أم قناة مدارة (relay)
            if self.process_source_channel_post(message):
                return
            if self.auto_relay_channel_post(message):
                return

        # فحص هل الأدمن أرسل استيكر لحفظه في المكتبة (بدون فئة محددة)
        if 'sticker' in message and self.is_admin(message['from']['id']):
            current_state_check = self.user_states.get(message['from']['id'], '')
            if not isinstance(current_state_check, str) or not current_state_check.startswith('stk_waiting_'):
                # حفظ مباشر بدون فئة
                sticker = message['sticker']
                item_id = f"STK{str(int(datetime.now().timestamp()))[-6:]}"
                try:
                    with open('sticker_library.csv', 'a', newline='', encoding='utf-8-sig') as f:
                        writer = csv.writer(f)
                        writer.writerow([item_id, 'sticker', sticker.get('file_id', ''),
                                       sticker.get('emoji', '🎨'), sticker.get('set_name', ''),
                                       self.tr('a0157_أخرى', 'ar'), message['from']['id'], datetime.now().strftime('%Y-%m-%d %H:%M')])
                except:
                    pass
                self.send_message(message['chat']['id'],
                    f"✅ <b>تم حفظ الاستيكر في المكتبة!</b>\n"
                    f"🎨 {sticker.get('emoji', '🎨')}\n"
                    f"🆔 <code>{item_id}</code>\n"
                    f"📂 فئة: أخرى")
                return

        text = message.get('text', '')
        # تطبيع نص الأزرار المعدلة إلى النص الأصلي حتى يستمر النظام في العمل كما هو
        text = self.normalize_button_text(text)
        chat_id = message['chat']['id']
        user_id = message['from']['id']
        
        # معالجة جميع الحالات أولاً (قبل الـ rate limiter)
        # لأن المستخدم في حالة نشطة يجب ألا يُحظر
        current_state = self.user_states.get(user_id, '')
        
        # زر إعادة التعيين يعمل من أي حالة — أولوية قصوى
        _all_langs_reset = {self.tr('reset_system', l) for l in self.get_supported_languages()}
        _all_langs_reset |= {self.tr('main_menu', l) for l in self.get_supported_languages()}
        _all_langs_reset |= {'🔄 إعادة ضبط النظام', '🔄 Reset', '🏠 الرئيسية', '🏠', 'reset', 'fix', 'إصلاح'}
        if text in _all_langs_reset:
            user = self.find_user(user_id)
            if user:
                self.super_reset_user_system(user_id, chat_id, user)
            else:
                self.handle_start(message)
            return
        
        if current_state == 'phone_login_waiting':
            self.handle_phone_login(message)
            return
        if current_state == 'verify_phone_waiting':
            # استقبال رقم الهاتف الحقيقي لاستبداله
            if 'contact' in message:
                phone = message['contact']['phone_number']
                if not phone.startswith('+'):
                    phone = '+' + phone
                user_id = message['from']['id']
                # تحديث رقم الهاتف في users.csv
                try:
                    rows = []
                    with open('users.csv', 'r', encoding='utf-8-sig') as f:
                        reader = csv.DictReader(f)
                        fieldnames = reader.fieldnames
                        for row in reader:
                            if row.get('telegram_id') == str(user_id):
                                row['phone'] = phone
                                row['phone_verified'] = 'yes'
                            rows.append(row)
                    with open('users.csv', 'w', newline='', encoding='utf-8-sig') as f:
                        writer = csv.DictWriter(f, fieldnames=fieldnames)
                        writer.writeheader()
                        writer.writerows(rows)
                except:
                    pass
                del self.user_states[user_id]
                # إشعار النجاح ثم إعادة توجيه حسب المصدر
                fake_msg = {'chat': {'id': message['chat']['id']}, 'from': {'id': message['from']['id']}, 'text': ''}
                self.send_message(message['chat']['id'],
                    f"✅ <b>تم تسجيل رقم هاتفك الحقيقي بنجاح!</b>\n\n"
                    f"📱 الرقم: <code>{phone}</code>\n"
                    f"✅ تم التحقق: <b>نعم</b>\n\n"
                    f"يمكنك الآن المشاركة في اليانصيب وعجلة الحظ")
                # توجيه ذكي — لو القادم من عجلة الحظ، اعرضها. لو من اليانصيب، اعرضه.
                # افحص آخر تفاعل — لو كان wheel، اعرض wheel. افتراضياً اعرض اليانصيب.
                self.show_lottery_panel(fake_msg)
                return
            elif message.get('text', '').strip().lower() in [self.tr('a0010_إلغاء', 'ar'), self.tr('a0011_الغاء', 'ar'), 'cancel', '🔙']:
                del self.user_states[user_id]
                self.handle_start(message)
            else:
                self.send_message(message['chat']['id'], self.tr('a0158_اضغط_زر', 'ar'))
            return
        if current_state == 'choosing_start_language':
            self.handle_start_language_choice(message)
            return
        if current_state == 'start_phone_input':
            self.handle_start_phone(message)
            return
        if isinstance(current_state, str) and current_state.startswith('registering_phone_'):
            self.handle_registration(message)
            return
        if isinstance(current_state, str) and current_state.startswith('registering'):
            self.handle_registration(message)
            return
        # فحوص SVRP المحددة قبل الفحص العام svrp_
        if isinstance(current_state, str) and current_state.startswith('svrp_enter_account_'):
            # إدخال رقم حساب في شركة استرداد
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            text = message.get('text', '').strip()

            if text in [self.tr('a0010_إلغاء', 'ar'), self.tr('a0011_الغاء', 'ar'), '🔙']:
                if user_id in self.user_states: del self.user_states[user_id]
                fake_msg = {'chat': {'id': chat_id}, 'from': {'id': user_id}, 'text': ''}
                self.show_svrp_panel(fake_msg)
                return

            parts = current_state.replace('svrp_enter_account_', '').split('_', 1)
            if len(parts) != 2:
                return
            company_id = parts[0]
            company_name = parts[1]

            if len(text) < 3:
                self.send_message(chat_id, self.tr('a0159_رقم_الحساب', 'ar'))
                return

            success, msg = self.svrp.add_user_company_account(user_id, company_id, company_name, text)
            if success:
                self.send_message(chat_id,
                    f"✅ {msg}\n\n"
                    f"🏆 يمكنك الآن طلب المكافأة من الأدمن.\n"
                    f"أو تسجيل حساب في شركة أخرى.")
                # عرض الشركات مرة أخرى للتسجيل في شركة أخرى
                companies = self.svrp.get_recovery_companies()
                accounts = self.svrp.get_user_company_accounts(user_id)
                registered_ids = {a['company_id'] for a in accounts}

                inline_btns = []
                for c in companies:
                    if c['id'] not in registered_ids:
                        inline_btns.append([{'text': f"📝 تسجيل حساب — {c['name']}", 'callback_data': f'svrp_reg_{c["id"]}'}])
                if not any(inline_btns):
                    inline_btns.append([{'text': '✅ تم تسجيل حسابك في جميع الشركات', 'callback_data': 'svrp_back_panel'}])
                else:
                    inline_btns.append([{'text': '🏆 طلب مكافأة', 'callback_data': f'svrp_bonus_{company_id}_{company_name}'}])
                inline_btns.append([{'text': '🔙 رجوع', 'callback_data': 'svrp_back_panel'}])
                self.send_inline_message(chat_id, self.tr('a0160_اختر_شركة', 'ar'), inline_btns)
            else:
                self.send_message(chat_id, f"❌ {msg}")

            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        if isinstance(current_state, str) and current_state.startswith('svrp_bonus_amount_'):
            # الأدمن يكتب مبلغ المكافأة
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            req_id = current_state.replace('svrp_bonus_amount_', '')
            text = message.get('text', '').strip()

            try:
                amount = float(text)
                if amount <= 0:
                    self.send_message(chat_id, self.tr('a0144_المبلغ_يجب', 'ar'))
                    return
            except ValueError:
                self.send_message(chat_id, self.tr('a0145_اكتب_مبلغاً', 'ar'))
                return

            success, msg = self.svrp.approve_bonus_request(req_id, amount, user_id)
            icon = "✅" if success else "❌"
            self.send_message(chat_id, f"{icon} {msg}", self.admin_keyboard())

            if success:
                bonus_req = None
                for r in self.svrp._read_csv('bonus_requests.csv'):
                    if r['id'] == req_id:
                        bonus_req = r
                        break
                if bonus_req:
                    self.notify_user(int(bonus_req['user_id']),
                        f"✅ <b>تمت الموافقة على طلب المكافأة!</b>\n\n"
                        f"💎 الشركة: {bonus_req.get('company_name', '')}\n"
                        f"💰 المبلغ: <code>{amount:.2f}</code>\n"
                        f"🧊 حالة الرصيد: <b>مجمد</b>",
                        'bonus_approved')

            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        if current_state == 'svrp_waiting_screenshot':
            # استقبال لقطة الشاشة للاسترداد
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            user = self.find_user(user_id)

            if 'photo' not in message:
                self.send_message(chat_id, self.tr('a0161_يرجى_إرسال', 'ar'))
                return

            # الحصول على أكبر حجم صورة
            photo = message['photo'][-1]
            photo_file_id = photo['file_id']

            if not user:
                self.send_message(chat_id, self.tr('a0149_يجب_التسجيل', 'ar'))
                if user_id in self.user_states: del self.user_states[user_id]
                return

            # إنشاء طلب استرداد
            req_id = self.svrp.create_recovery_request(
                user_id, user.get('customer_id', ''), photo_file_id
            )

            # إشعار المستخدم
            self.send_message(chat_id,
                f"✅ <b>تم إرسال طلب الاسترداد</b>\n\n"
                f"🆔 <code>{req_id}</code>\n"
                f"⏳ بانتظار مراجعة الإدارة",
                self.main_keyboard(user.get('language', 'ar'), user_id))

            # إرسال الصورة للأدمن + أزرار موافقة/رفض
            for admin_id in self.admin_ids:
                try:
                    admin_msg = (
                        f"🔄 <b>طلب استرداد جديد</b>\n\n"
                        f"🆔 <code>{req_id}</code>\n"
                        f"👤 العميل: <code>{user.get('customer_id', '')}</code>\n"
                        f"📅 {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\n"
                        f"📸 لقطة الشاشة:"
                    )
                    inline_btns = [
                        [{'text': '✅ موافقة', 'callback_data': f'svrp_recovery_approve_{req_id}'},
                         {'text': '❌ رفض', 'callback_data': f'svrp_recovery_reject_{req_id}'}]
                    ]
                    # إرسال الصورة + الأزرار
                    self.api_call('sendPhoto', {
                        'chat_id': admin_id,
                        'photo': photo_file_id,
                        'caption': admin_msg,
                        'parse_mode': 'HTML',
                        'reply_markup': json.dumps({'inline_keyboard': [
                            [{'text': '✅ موافقة', 'callback_data': f'svrp_recovery_approve_{req_id}'},
                             {'text': '❌ رفض', 'callback_data': f'svrp_recovery_reject_{req_id}'}]
                        ]})
                    })
                except Exception as e:
                    logger.error(f"خطأ في إشعار الأدمن بطلب الاسترداد: {e}")

            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        if isinstance(current_state, str) and current_state.startswith('svrp_recovery_amount_'):
            # الأدمن يكتب مبلغ الاسترداد بعد الموافقة
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            req_id = current_state.replace('svrp_recovery_amount_', '')
            text = message.get('text', '').strip()

            try:
                amount = float(text)
                if amount <= 0:
                    self.send_message(chat_id, self.tr('a0144_المبلغ_يجب', 'ar'))
                    return
            except ValueError:
                self.send_message(chat_id, self.tr('a0145_اكتب_مبلغاً', 'ar'))
                return

            success, msg = self.svrp.approve_recovery_request(req_id, user_id, amount)
            icon = "✅" if success else "❌"
            self.send_message(chat_id, f"{icon} {msg}", self.admin_keyboard())

            # إشعار المستخدم
            req = self.svrp.get_recovery_request(req_id)
            if req and success:
                self.notify_user(int(req['user_id']),
                    f"✅ <b>تمت الموافقة على استردادك!</b>\n\n"
                    f"💎 الرصيد المضاف: <code>{amount:.2f}</code>\n"
                    f"🧊 حالة الرصيد: <b>مجمد</b>\n\n"
                    f"💡 أرسل رصيداً لأصدقائك لفك التجميد",
                    'recovery_approved')

            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        if isinstance(current_state, str) and current_state.startswith('svrp_dep_balance_'):
            # إيداع من الرصيد المتاح
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            text = message.get('text', '').strip()

            if text in [self.tr('a0010_إلغاء', 'ar'), self.tr('a0011_الغاء', 'ar'), '🔙']:
                if user_id in self.user_states: del self.user_states[user_id]
                fake_msg = {'chat': {'id': chat_id}, 'from': {'id': user_id}, 'text': ''}
                self.show_svrp_panel(fake_msg)
                return

            parts = current_state.replace('svrp_dep_balance_', '').split('_', 1)
            if len(parts) != 2:
                return
            company_id = parts[0]
            company_name = parts[1]

            try:
                amount = float(text)
                if amount <= 0:
                    self.send_message(chat_id, self.tr('a0144_المبلغ_يجب', 'ar'))
                    return
            except ValueError:
                self.send_message(chat_id, self.tr('a0162_اكتب_مبلغاً', 'ar'))
                return

            # الحصول على رقم حساب المستخدم في الشركة
            account = self.svrp.get_user_company_account(user_id, company_id)
            if not account:
                self.send_message(chat_id, self.tr('a0163_لا_يوجد', 'ar'))
                if user_id in self.user_states: del self.user_states[user_id]
                return

            # تنفيذ الإيداع من المتاح
            success, msg = self.svrp.deposit_from_balance(user_id, company_id, company_name, amount)
            if success:
                user = self.find_user(user_id)
                user_currency = user.get('currency', 'SAR') if user else 'SAR'

                self.send_message(chat_id,
                    f"✅ <b>تم طلب الإيداع!</b>\n\n"
                    f"🆔 <code>{msg}</code>\n"
                    f"🏢 الشركة: {company_name}\n"
                    f"📋 رقم حسابك: <code>{account.get('account_number', '')}</code>\n"
                    f"💰 المبلغ: <b>{amount:.2f}</b> {user_currency}\n\n"
                    f"⏳ سيتم مراجعة طلبك من الإدارة")

                # إشعار الأدمن
                for admin_id in self.admin_ids:
                    try:
                        admin_msg = (
                            f"💰 <b>طلب إيداع من رصيد متاح</b>\n\n"
                            f"🆔 <code>{msg}</code>\n"
                            f"👤 العميل: {user.get('name', '')} ({user.get('customer_id', '')})\n"
                            f"🏢 الشركة: {company_name}\n"
                            f"📋 رقم الحساب: <code>{account.get('account_number', '')}</code>\n"
                            f"💰 المبلغ: <b>{amount:.2f}</b> {user_currency}\n\n"
                        )
                        inline_btns = [
                            [{'text': '✅ تأكيد', 'callback_data': f'svrp_dep_approve_{msg}'},
                             {'text': '❌ رفض', 'callback_data': f'svrp_dep_reject_{msg}'}]
                        ]
                        self.send_inline_message(admin_id, admin_msg, inline_btns)
                    except Exception as e:
                        logger.error(f"خطأ في إشعار الأدمن بالإيداع: {e}")
            else:
                self.send_message(chat_id, f"❌ {msg}")

            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        if isinstance(current_state, str) and current_state == 'svrp_send_customer':
            # إرسال رصيد مجمد خطوة 1: معرف العميل
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            text = message.get('text', '').strip()
            if text in [self.tr('a0010_إلغاء', 'ar'), self.tr('a0011_الغاء', 'ar'), '🔙']:
                if user_id in self.user_states: del self.user_states[user_id]
                fake_msg = {'chat': {'id': chat_id}, 'from': {'id': user_id}, 'text': ''}
                self.show_svrp_panel(fake_msg)
                return
            target_customer_id = text
            kb = {'keyboard': [[{'text': '❌ إلغاء'}]], 'resize_keyboard': True, 'one_time_keyboard': True}
            self.send_message(chat_id,
                f"✅ معرف العميل: <code>{target_customer_id}</code> 👈 اضغط للنسخ\n\n"
                f"2️⃣ اكتب <b>المبلغ</b>:", kb)
            self.user_states[user_id] = f'svrp_send_amount_{target_customer_id}'

        if isinstance(current_state, str) and current_state.startswith('svrp_send_amount_'):
            # إرسال رصيد مجمد خطوة 2: المبلغ
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            text = message.get('text', '').strip()
            if text in [self.tr('a0010_إلغاء', 'ar'), self.tr('a0011_الغاء', 'ar'), '🔙']:
                if user_id in self.user_states: del self.user_states[user_id]
                fake_msg = {'chat': {'id': chat_id}, 'from': {'id': user_id}, 'text': ''}
                self.show_svrp_panel(fake_msg)
                return
            target_customer_id = current_state.replace('svrp_send_amount_', '')
            try:
                amount = float(text)
                if amount <= 0:
                    self.send_message(chat_id, self.tr('a0144_المبلغ_يجب', 'ar'))
                    return
            except ValueError:
                self.send_message(chat_id, self.tr('a0145_اكتب_مبلغاً', 'ar'))
                return
            success, msg = self.svrp.send_frozen_credits(str(user_id), target_customer_id, amount)
            icon = "✅" if success else "❌"
            self.send_message(chat_id, f"{icon} {msg}")
            if success:
                try:
                    with open('users.csv', 'r', encoding='utf-8-sig') as f:
                        reader = csv.DictReader(f)
                        for row in reader:
                            if row.get('customer_id', '') == target_customer_id:
                                recv_tid = row.get('telegram_id', '')
                                if recv_tid:
                                    self.notify_user(int(recv_tid),
                                        f"📥 <b>تم استلام رصيد مجمد!</b>\n\n"
                                        f"💰 المبلغ: <code>{amount:.2f}</code> 👈 اضغط للنسخ\n"
                                        f"🧊 حالة الرصيد: <b>مجمد</b>\n\n"
                                        f"💡 أرسل رصيداً لأصدقائك لفك التجميد")
                                break
                except:
                    pass
            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        if isinstance(current_state, str) and current_state.startswith('svrp_approve_amount_'):
            # الأدمن يكتب مبلغ الاسترداد للموافقة
            user_id = message['from']['id']
            chat_id = message['chat']['id']
            text = message.get('text', '').strip()
            req_id = current_state.replace('svrp_approve_amount_', '')
            try:
                amount = float(text)
                if amount <= 0:
                    self.send_message(chat_id, self.tr('a0144_المبلغ_يجب', 'ar'))
                    return
                success, msg = self.svrp.approve_recovery_request(req_id, amount, user_id)
                if success:
                    self.send_message(chat_id, f"✅ {msg}", self.admin_keyboard())
                    req = self.svrp.get_recovery_request(req_id)
                    if req:
                        self.notify_user(int(req['user_id']),
                            f"✅ <b>تمت الموافقة على طلب استردادك!</b>\n\n"
                            f"💰 تم إضافة <b>{amount:.2f}</b> لرصيدك المجمد 🧊\n\n"
                            f"💡 أرسل رصيداً لأصدقائك لفك التجميد")
                else:
                    self.send_message(chat_id, f"❌ {msg}", self.admin_keyboard())
            except ValueError:
                self.send_message(chat_id, self.tr('a0162_اكتب_مبلغاً', 'ar'))
                return
            if user_id in self.user_states:
                del self.user_states[user_id]
            return

        # باقي حالات svrp_ (أكواد ترويجية، إلخ)
        if isinstance(current_state, str) and current_state.startswith('svrp_'):
            self.handle_svrp_state(message, current_state)
            return

