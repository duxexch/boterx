def translate_arabic_to_english(text):
    """Translate using word-boundary regex to avoid partial matches."""
    result = text
    # Sort by length (longest first) to match phrases before individual words
    for ar, en in sorted(TRANSLATIONS.items(), key=lambda x: len(x[0]), reverse=True):
        if not ar or not en:
            continue
        # Use regex with word boundaries for Arabic text
        # Arabic word characters: \u0600-\u06FF plus Arabic diacritics
        pattern = r'(?<![\u0600-\u06FF])' + re.escape(ar) + r'(?![\u0600-\u06FF])'
        result = re.sub(pattern, en, result)
    return result

def translate_value(key, ar_value):
    """Translate an Arabic string to English."""
    if not re.search(r'[\u0600-\u06FF]', ar_value):
        return ar_value
    translated = translate_arabic_to_english(ar_value)
    translated = re.sub(r'  +', ' ', translated)
    translated = re.sub(r'\s+([,.!?])', r'\1', translated)
    if translated and translated[0].isalpha():
        translated = translated[0].upper() + translated[1:]
    return translated

